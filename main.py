# Словари слов
pos = ["красивый", "отличный", "хороший", "быстрый", "удобный", "нравится",
       "доволен", "рекомендую", "супер", "яркий", "соответствует", "вернули"]
neg = ["плохой", "ужасный", "медленный", "тормозит", "глючит", "брак",
       "разряжается", "перегревается", "разочарован", "тяжёлый", "не",
       "отключился", "отключилась", "сломался", "сломаллась", "долго",
       "работал", "включился", "завис"]
neu = ["экран", "батарея", "камера", "телефон", "процессор", "память",
       "корпус", "дюйм", "гб", "цена", "описание", "описанию", "работы",
       "работа", "месяца", "месяц", "пол", "раз", "раза", "деньги"]

while True:
    # Ввод отзыва
    text = input("Введите отзыв (или 'выход'): ").lower()
    if text == "выход":
        break

    # Убираем знаки препинания
    for ch in ".,!?;:()[]«»\"'—–-":
        text = text.replace(ch, " ")

    # Разбиваем на слова
    words = text.split()

    # Классифицируем
    p, n, u = [], [], []
    for w in words:
        if w in pos:
            p.append(w)
        elif w in neg:
            n.append(w)
        elif w in neu:
            u.append(w)

    # Общая оценка
    if len(p) == 0 and len(n) == 0:
        itog = "нейтральный"
    elif len(p) > len(n):
        itog = "положительный"
    elif len(n) > len(p):
        itog = "отрицательный"
    else:
        itog = "смешанный"

    # Вывод
    print("Положительные:", p)
    print("Отрицательные:", n)
    print("Нейтральные:", u)
    print("Общая оценка:", itog)
    print()